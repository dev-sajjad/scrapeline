"""Generate drift cases: single-mutation copies of the static-list fixture site.

    uv run python scripts/build_drift.py

Each case = tests/sites/drift/<case>/{index,page2,page3}.html + case.json.
Content (meetings) never changes, so every case is graded against the same golden rows
(tests/fixtures/golden/static-list.json). Mutations mirror real municipal site redesigns.
"""

from __future__ import annotations

import json
import re
import shutil
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tests" / "sites" / "static-list"
OUT = ROOT / "tests" / "sites" / "drift"
PAGES = ("index.html", "page2.html", "page3.html")

Mutation = Callable[[str], str]


def sub(pattern: str, repl: str) -> Mutation:
    return lambda html: re.sub(pattern, repl, html)


def chain(*fns: Mutation) -> Mutation:
    def run(html: str) -> str:
        for fn in fns:
            html = fn(html)
        return html

    return run


def cards(html: str) -> str:
    """Table -> div cards (full layout redesign)."""
    html = re.sub(
        r"<table class='meetings'>.*?<tbody>", "<div class='meeting-list'>", html, flags=re.S
    )
    html = html.replace("</tbody></table>", "</div>")
    html = re.sub(r"<tr data-id='([^']+)'>", r"<article class='meeting-card' data-id='\1'>", html)
    html = html.replace("</td></tr>", "</div></article>")
    html = re.sub(r"<td class='(\w+)'>", r"<div class='card-\1'>", html)
    return html.replace("</td>", "</div>")


def date_to_attr(html: str) -> str:
    """Visible date becomes relative text; machine date moves to <time datetime>."""
    return re.sub(
        r"<td class='date'>([^<]+)</td>",
        lambda m: f"<td class='date'><time datetime='{m.group(1)}'>see calendar</time></td>",
        html,
    )


CASES: dict[str, tuple[str, Mutation, bool]] = {
    # name: (description, mutation, breaks_reference_spec)
    "01-title-class-renamed": (
        "td.title renamed to td.meeting-name",
        sub(r"class='title'", "class='meeting-name'"),
        True,
    ),
    "02-table-class-renamed": (
        "table.meetings renamed to table.meeting-table",
        sub(r"<table class='meetings'>", "<table class='meeting-table'>"),
        True,
    ),
    "03-date-moved-to-attribute": (
        "visible date replaced by text; ISO-ish value in <time datetime>",
        date_to_attr,
        True,
    ),
    "04-agenda-link-class": (
        "a.agenda renamed to a.doc-link-agenda",
        sub(r"class='agenda'", "class='doc-link-agenda'"),
        True,
    ),
    "05-next-link-changed": (
        "rel=next removed; pager uses a.pager-next",
        sub(r"<a rel='next' class='next'", "<a class='pager-next'"),
        True,
    ),
    "06-table-to-cards": ("table layout replaced with article cards", cards, True),
    "07-status-badge": (
        "em.status replaced by span.badge.badge-cancelled",
        sub(
            r"<em class='status'>CANCELLED</em>",
            "<span class='badge badge-cancelled'>Cancelled</span>",
        ),
        True,
    ),
    "08-id-attribute-renamed": (
        "data-id renamed to data-meeting-key",
        sub(r"data-id=", "data-meeting-key="),
        True,
    ),
    "09-cosmetic-only": (
        "wrapper div + inline styles added; selectors still valid (no repair needed)",
        chain(
            sub(r"<main>", "<main><div class='container' style='padding:1em'>"),
            sub(r"</main>", "</div></main>"),
        ),
        False,
    ),
    "10-location-column-moved": (
        "location column moved before date and renamed td.venue",
        chain(
            sub(
                r"(<td class='date'>[^<]*</td><td class='time'>[^<]*</td>)<td class='location'>([^<]*)</td>",
                r"<td class='venue'>\2</td>\1",
            )
        ),
        True,
    ),
}


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    for name, (desc, mutate, breaks) in CASES.items():
        case_dir = OUT / name
        case_dir.mkdir(parents=True)
        for page in PAGES:
            (case_dir / page).write_text(mutate((SRC / page).read_text()))
        (case_dir / "case.json").write_text(
            json.dumps(
                {
                    "case": name,
                    "base_site": "static-list",
                    "source_id": "fixture-static-list",
                    "description": desc,
                    "breaks_reference_spec": breaks,
                    "golden": "static-list",
                },
                indent=1,
            )
            + "\n"
        )
    (OUT / "README.md").write_text(
        "# Drift cases\n\nGenerated by `scripts/build_drift.py`: one mutation of `static-list/` per case.\n"
        "All cases are graded against `tests/fixtures/golden/static-list.json` (content unchanged).\n\n"
        "| Case | Mutation | Breaks reference spec |\n|---|---|---|\n"
        + "".join(
            f"| {n} | {d} | {'yes' if b else 'no (control)'} |\n" for n, (d, _, b) in CASES.items()
        )
    )
    print(f"drift cases: {len(CASES)}")


if __name__ == "__main__":
    main()
