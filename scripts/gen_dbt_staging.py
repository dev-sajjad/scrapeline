"""Generate the dbt lake sources and the typed per-dataset staging models.

The sources file comes from the lake layout (`scrapeline.analytics.layout.TABLES`). Each
generic dataset type in the schema registry gets a staging model `stg_<dataset>__versions`
with one typed column per field, so a new dataset type gets a model by re-running this:

    uv run python scripts/gen_dbt_staging.py           # write the files under dbt/models/staging
    uv run python scripts/gen_dbt_staging.py --check   # exit 1 when the committed files are stale

Typed datasets (the civic pack) are skipped: they keep their own tables and have no version
history in the lake. When a dataset has several versions, the model has the union of their
fields and each field takes its type from the newest version that defines it; payloads of
versions that gave the field another type are cast with `try_cast`, so an old value that does
not convert is empty instead of failing the build. Personal-data fields (`pii`) get no
`not_null` test: the record store blanks them unless the source's usage allows personal data.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from scrapeline.analytics.layout import LAKE_LAYOUT_VERSION, TABLES, LakeTable
from scrapeline.catalog.datasets import DatasetRegistry, DatasetType, FieldDef, default_registry

ROOT = Path(__file__).resolve().parents[1]
DBT_DIR = ROOT / "dbt"
SOURCES_FILE = Path("models/staging/lake/_lake__sources.yml")
DATASETS_DIR = Path("models/staging/datasets")
DATASETS_FILE = DATASETS_DIR / "_datasets__models.yml"
GENERATED = "Generated by scripts/gen_dbt_staging.py; re-run it instead of editing."
# dbt renders this when it parses the sources; a relative path resolves from the directory
# dbt runs in, which is the repository root.
LAKE_DIR = "{{ env_var('LAKE_DIR', 'data/lake') }}"

SQL_TYPES = {
    "text": "VARCHAR",
    "url": "VARCHAR",
    "enum": "VARCHAR",
    "int": "BIGINT",
    "float": "DOUBLE",
    "decimal": "DECIMAL(38, 10)",
    "bool": "BOOLEAN",
    "date": "DATE",
    "datetime": "TIMESTAMPTZ",
    "time": "TIME",
}
MONEY_AMOUNT = "DECIMAL(18, 4)"
CHANGE_TYPES = ["insert", "update", "removed", "restored"]
NOT_REMOVED = "change_type <> 'removed'"

# Columns every dataset model takes from stg_lake__record_versions, with their tests.
VERSION_COLUMNS: dict[str, tuple[str, list[Any]]] = {
    "version_id": ("Lake primary key of the version.", ["unique", "not_null"]),
    "record_id": ("The record (identity) this version belongs to.", ["not_null"]),
    "source_id": ("Source that observed the record.", ["not_null"]),
    "dataset_version": ("Dataset type version the payload was written with.", ["not_null"]),
    "external_id": ("Identity of the record within its source.", ["not_null"]),
    "version": ("1, 2, 3... per record; order history by this.", ["not_null"]),
    "change_type": (
        "insert, update, removed or restored.",
        [{"accepted_values": {"arguments": {"values": CHANGE_TYPES}}}],
    ),
    "valid_from": ("When this version became the record's state (UTC).", ["not_null"]),
    "content_hash": ("Hash of the normalised payload; empty for removals.", []),
    "run_id": ("Run that wrote the version.", ["not_null"]),
    "raw_sha256": ("Raw response the version was parsed from; empty for removals.", []),
    "scraper_version_id": ("Scraper version that parsed it.", []),
}


@dataclass(frozen=True)
class StagingColumn:
    name: str
    expression: str
    data_type: str
    description: str
    required: bool = False
    values: tuple[str, ...] | None = None
    pii: bool = False


def lake_sources_yaml(tables: Mapping[str, LakeTable]) -> str:
    """dbt sources for every lake table, read straight from Parquet by dbt-duckdb."""
    entries = [_source_table(table) for table in tables.values()]
    doc = {
        "version": 2,
        "sources": [
            {
                "name": "lake",
                "description": (
                    f"Parquet lake written by the exporter (layout version {LAKE_LAYOUT_VERSION}, "
                    "analytics/layout.py). Append tables can hold the same row in several "
                    "exports; staging models dedupe them on their primary key."
                ),
                "tables": entries,
            }
        ],
    }
    return _yaml(doc)


def _source_table(table: LakeTable) -> dict[str, Any]:
    options = ["filename = true"]
    if table.mode == "append":
        options = ["hive_partitioning = true", "union_by_name = true", *options]
    path = f"{LAKE_DIR}/{table.glob}"
    if table.mode == "append":
        description = (
            f"Append table, partitioned by {', '.join(table.partition_by)}; exported "
            f"incrementally by `{table.watermark}` ({table.late_commits} rule)."
        )
    else:
        description = "Snapshot table, rewritten whole on every export."
    return {
        "name": table.name,
        "description": description,
        "config": {
            "external_location": f"read_parquet('{path}', {', '.join(options)})",
            # The same path for the macro that checks whether the exporter wrote any file yet.
            "meta": {"lake_path": path, "mode": table.mode},
        },
        "columns": [{"name": c.name, "data_type": c.type} for c in table.columns],
    }


def staging_columns(versions: Sequence[DatasetType]) -> list[StagingColumn]:
    """Typed columns for every field of every version, newest definition first."""
    newest_first = sorted(versions, key=lambda ds: ds.version, reverse=True)
    fields: dict[str, FieldDef] = {}
    for ds in newest_first:
        for name, f in ds.fields.items():
            fields.setdefault(name, f)
    # A field is required only if every version requires it; old payloads may lack it.
    required = {
        name
        for name in fields
        if all(name in ds.fields and ds.fields[name].required for ds in versions)
    }
    values: dict[str, set[str]] = {}
    pii: set[str] = set()
    for ds in versions:
        for name, f in ds.fields.items():
            if f.values:
                values.setdefault(name, set()).update(f.values)
            if f.pii:
                pii.add(name)

    columns: list[StagingColumn] = []
    for name, f in fields.items():
        column = f"{name}_value" if name in VERSION_COLUMNS else name
        about = f.description or name.replace("_", " ").capitalize()
        if column != name:
            about += f" (field `{name}`)"
        flags = ", ".join(
            x for x in (f.type, "key" if f.key else "", "pii" if name in pii else "") if x
        )
        # Versions that gave the field another type; their payloads may not convert.
        other = sorted(ds.version for ds in versions if _type_of(ds, name) not in (None, f.type))
        if other:
            about += f" (versions {', '.join(map(str, other))} had another type)"
        if f.type == "money":
            money = f"payload->'{name}'"
            columns += [
                StagingColumn(
                    f"{column}_amount",
                    _cast(f"{money}->>'amount'", MONEY_AMOUNT, other),
                    MONEY_AMOUNT,
                    f"{about}: amount ({flags}).",
                    name in required,
                    pii=name in pii,
                ),
                StagingColumn(
                    f"{column}_currency",
                    f"{money}->>'currency'",
                    "VARCHAR",
                    f"{about}: ISO 4217 currency ({flags}).",
                    name in required,
                    pii=name in pii,
                ),
            ]
            continue
        sql_type = SQL_TYPES[f.type]
        expression = f"payload->>'{name}'"
        if sql_type != "VARCHAR":
            expression = _cast(expression, sql_type, other)
        columns.append(
            StagingColumn(
                column,
                expression,
                sql_type,
                f"{about} ({flags}).",
                name in required,
                tuple(sorted(values[name])) if name in values else None,
                pii=name in pii,
            )
        )
    names = [c.name for c in columns]
    clashes = sorted({n for n in names if names.count(n) > 1 or n in VERSION_COLUMNS})
    if clashes:
        raise SystemExit(f"{versions[0].name}: staging column names clash: {clashes}")
    return columns


def _type_of(ds: DatasetType, name: str) -> str | None:
    f = ds.fields.get(name)
    return f.type if f is not None else None


def _cast(expression: str, sql_type: str, loose_versions: Sequence[int]) -> str:
    """A cast that fails loudly for the column's own type, and `try_cast` for older types."""
    if not loose_versions:
        return f"cast({expression} as {sql_type})"
    listed = ", ".join(map(str, loose_versions))
    return (
        f"case when dataset_version in ({listed}) then try_cast({expression} as {sql_type}) "
        f"else cast({expression} as {sql_type}) end"
    )


def dataset_model_sql(name: str, columns: Sequence[StagingColumn]) -> str:
    select = [*VERSION_COLUMNS, *(f"{c.expression} as {c.name}" for c in columns)]
    lines = ",\n".join(f"    {item}" for item in select)
    return (
        f"-- {GENERATED}\n"
        f"select\n{lines}\n"
        "from {{ ref('stg_lake__record_versions') }}\n"
        f"where dataset = '{name}'\n"
    )


def dataset_models_yaml(models: Mapping[str, tuple[DatasetType, list[StagingColumn]]]) -> str:
    entries = []
    for name, (latest, columns) in models.items():
        meta_columns = [
            {"name": col, "description": about, **({"data_tests": tests} if tests else {})}
            for col, (about, tests) in VERSION_COLUMNS.items()
        ]
        field_columns = [_column_entry(c) for c in columns]
        entries.append(
            {
                "name": f"stg_{name}__versions",
                "description": (
                    f"Every version of `{name}` records with typed columns (dataset pack "
                    f"{latest.pack}, latest version {latest.version}): {latest.description} "
                    "Field columns are empty on `removed` versions."
                ),
                "columns": meta_columns + field_columns,
            }
        )
    return _yaml({"version": 2, "models": entries})


def _column_entry(column: StagingColumn) -> dict[str, Any]:
    tests: list[Any] = []
    # Personal data is blanked unless the source may keep it, so it can be empty by design.
    if column.required and not column.pii:
        tests.append({"not_null": {"config": {"where": NOT_REMOVED}}})
    if column.values:
        tests.append({"accepted_values": {"arguments": {"values": list(column.values)}}})
    entry: dict[str, Any] = {
        "name": column.name,
        "description": column.description,
        "data_type": column.data_type,
    }
    if tests:
        entry["data_tests"] = tests
    return entry


def render(registry: DatasetRegistry, tables: Mapping[str, LakeTable]) -> dict[Path, str]:
    """Every generated file, keyed by its path relative to the dbt project."""
    by_name: dict[str, list[DatasetType]] = {}
    for ds in registry:
        if ds.storage == "generic":
            by_name.setdefault(ds.name, []).append(ds)
    models = {
        name: (max(versions, key=lambda ds: ds.version), staging_columns(versions))
        for name, versions in sorted(by_name.items())
    }
    files = {SOURCES_FILE: lake_sources_yaml(tables), DATASETS_FILE: dataset_models_yaml(models)}
    for name, (_, columns) in models.items():
        files[DATASETS_DIR / f"stg_{name}__versions.sql"] = dataset_model_sql(name, columns)
    return files


class _Dumper(yaml.SafeDumper):
    """Indented lists and no anchors, so the files read like hand-written dbt YAML."""

    def increase_indent(self, flow: bool = False, indentless: bool = False) -> None:
        super().increase_indent(flow, False)

    def ignore_aliases(self, data: Any) -> bool:
        return True


def _yaml(doc: Mapping[str, Any]) -> str:
    body = yaml.dump(dict(doc), Dumper=_Dumper, sort_keys=False, width=1000, allow_unicode=True)
    return f"# {GENERATED}\n{body}"


def _stale(dbt_dir: Path, files: Mapping[Path, str]) -> list[Path]:
    """Generated dataset models whose dataset no longer exists."""
    found = (dbt_dir / DATASETS_DIR).glob("stg_*__versions.sql")
    generated = (p for p in found if p.read_text().startswith(f"-- {GENERATED}"))
    return sorted(p.relative_to(dbt_dir) for p in generated if p.relative_to(dbt_dir) not in files)


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale files, write nothing")
    parser.add_argument("--dbt-dir", type=Path, default=DBT_DIR)
    args = parser.parse_args(list(argv) if argv is not None else None)

    files = render(default_registry(), TABLES)
    changed = [p for p, text in files.items() if _read(args.dbt_dir / p) != text]
    stale = _stale(args.dbt_dir, files)
    if args.check:
        for path in [*changed, *stale]:
            print(f"out of date: {path}")
        return 1 if changed or stale else 0
    for path in changed:
        target = args.dbt_dir / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(files[path])
        print(f"wrote {path}")
    for path in stale:
        (args.dbt_dir / path).unlink()
        print(f"removed {path}")
    return 0


def _read(path: Path) -> str | None:
    return path.read_text() if path.exists() else None


if __name__ == "__main__":
    sys.exit(main())
